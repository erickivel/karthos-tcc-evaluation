#!/bin/sh
set -eu
EVALUATION_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$EVALUATION_ROOT"
export PYTHONDONTWRITEBYTECODE=1
: "${CLOUDSDK_CONFIG:=${GKE_EVAL_CLOUDSDK_CONFIG:-$EVALUATION_ROOT/.work/gke/gcloud}}"
if [ -z "${GKE_EVAL_BOOTSTRAP_CONTEXT:-}" ] || [ -n "${GKE_EVAL_GOOGLE_APPLICATION_CREDENTIALS:-}" ]; then
  : "${GOOGLE_APPLICATION_CREDENTIALS:=${GKE_EVAL_GOOGLE_APPLICATION_CREDENTIALS:-$CLOUDSDK_CONFIG/application_default_credentials.json}}"
fi
export CLOUDSDK_CONFIG GOOGLE_APPLICATION_CREDENTIALS
exec python3 -B -m evaluation.gke "$@"
